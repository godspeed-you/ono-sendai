//! The volatile counts are measured, and the README cannot disagree with them (issue #111,
//! v0.4.1 §50).
//!
//! §50.1 forbids duplicating counts across README and docs "without automated verification", and
//! §50.3 says what the verification is: the README may keep the numbers, and the gate fails when
//! they disagree with generated truth. The exit test for the issue is the last one here — edit a
//! count in the README to a wrong value and the gate goes red.

#![allow(
    clippy::expect_used,
    clippy::unwrap_used,
    clippy::panic,
    reason = "AGENTS.md §16: a test states its preconditions directly"
)]

use ono_testkit::scratch;
use xtask::metrics::{check_readme, measure, write_readme};

