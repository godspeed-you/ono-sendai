#[test]
fn should_compute_every_metric_the_readme_states() {
    // §50.1's five counts, and the two §50.4 adds beside the test figure. Each is asserted as a
    // property of the tree rather than as a number, because the number is what changes daily and
    // the property is what §50 is about.
    let measured = measure(&repo());
    assert!(
        measured.crates >= 20,
        "the workspace has crates under `crates/`, got {}",
        measured.crates
    );
    assert_eq!(
        measured.workspace_members,
        measured.crates + 2,
        "§50.2's `crates` is the library count; the members are those plus `xtask` and `fuzz`, \
         and saying which is which is the difference between a metric and a number"
    );
    assert!(
        measured.tests > 1000,
        "test functions are counted, got {}",
        measured.tests
    );
    assert!(
        measured.acceptance_cases > 100,
        "acceptance cases are counted, got {}",
        measured.acceptance_cases
    );
    assert!(
        measured.adrs > 300,
        "decision records are counted, got {}",
        measured.adrs
    );
    assert!(
        measured.commands > measured.command_contract_files,
        "each contract file declares several commands, got {} in {} files",
        measured.commands,
        measured.command_contract_files
    );

    let rendered = measured.render();
    for key in [
        "crates=",
        "tests=",
        "acceptance_cases=",
        "adrs=",
        "commands=",
    ] {
        assert!(
            rendered.contains(key),
            "§50.2's example output names `{key}`: {rendered}"
        );
    }
}

#[test]
fn should_count_executed_tests_apart_from_skipped_ones() {
    // §50.4: "A README statement such as 'N tests pass' MUST not count skipped cases as proof of
    // execution." A static reading cannot know what a run executed, so the figure is named
    // `tests` for *declared* and two figures beside it carry the skip story — the count that can
    // skip, and the count the canonical CI environment expects to.
    let measured = measure(&repo());
    let rendered = measured.render();
    assert!(
        rendered.contains("tests_that_can_skip=") && rendered.contains("expected_ci_skips="),
        "the skip figures stand beside the test count rather than being folded into it: {rendered}"
    );
    assert!(
        measured.expected_ci_skips <= measured.tests_that_can_skip,
        "a test the canonical environment expects to skip is one that can skip: {} of {}",
        measured.expected_ci_skips,
        measured.tests_that_can_skip
    );
    assert!(
        measured.tests_that_can_skip < measured.tests,
        "most tests cannot skip at all; if every one could, §38.2's preferred count of zero would \
         be meaningless: {} of {}",
        measured.tests_that_can_skip,
        measured.tests
    );
}

