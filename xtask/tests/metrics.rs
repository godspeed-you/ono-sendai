#[test]
fn should_rewrite_the_block_and_leave_the_prose_around_it_alone() {
    // §50.3: "The original narrative text around it remains human-owned." A generator that
    // rewrote the paragraph would make the sentence somebody wrote a build artifact.
    let repo = scratch();
    repo.write("crates/ono-core/src/lib.rs", "//! one\n");
    repo.write(
        "README.md",
        "# Ono-Sendai\n\nThe deck is real this time.\n\n<!-- generated by `cargo xtask metrics`. -->\n\n```text\ncrates=99\n```\n\n<!-- end generated -->\n\nAnd the narrative continues.\n",
    );
    assert!(write_readme(repo.path()).expect("the README is rewritten"));
    let text = std::fs::read_to_string(repo.path().join("README.md")).expect("README.md");
    assert!(
        text.contains("The deck is real this time.")
            && text.contains("And the narrative continues."),
        "the human-owned prose survives: {text}"
    );
    assert!(text.contains("crates=1") && !text.contains("crates=99"));
    assert!(
        !write_readme(repo.path()).expect("the second run is a no-op"),
        "a second run changes nothing, so the generator is not a source of diff noise"
    );
    assert_eq!(check_readme(repo.path()), Vec::new());
}

