fn commands_page(families: &BTreeMap<String, Yaml>) -> String {
    let mut page = header(
        "Command reference",
        "Every command Ono defines, grouped by family. `stability` says whether the contract is a \
         promise; `phase` says which phase of spec §37 delivers it.",
    );

    for (file, document) in families {
        let family = string_at(document, "family").unwrap_or_else(|| file.clone());
        let _ = write!(page, "\n## {family}\n");

        for command in sequence(document, "commands") {
            let id = string_at(command, "id").unwrap_or_default();
            let verb = string_at(command, "verb").unwrap_or_default();
            let target = string_at(command, "target").unwrap_or_default();
            let invocation = if target.is_empty() || target == "null" {
                verb.clone()
            } else {
                format!("{verb} {target}")
            };

            let _ = write!(page, "\n### `{invocation}`\n\n");
            let _ = writeln!(
                page,
                "{}\n",
                string_at(command, "summary").unwrap_or_default()
            );
            let _ = writeln!(page, "| | |\n|---|---|");
            let _ = writeln!(page, "| id | `{id}` |");
            let _ = writeln!(
                page,
                "| stability | {} |",
                string_at(command, "stability").unwrap_or_else(|| "unspecified".to_owned())
            );
            let _ = writeln!(
                page,
                "| phase | {} |",
                string_at(command, "phase").unwrap_or_else(|| "unspecified".to_owned())
            );
            let _ = writeln!(
                page,
                "| input | `{}` |",
                string_at(command, "input").unwrap_or_else(|| "null".to_owned())
            );
            let _ = writeln!(
                page,
                "| output | `{}` |",
                string_at(command, "output").unwrap_or_else(|| "null".to_owned())
            );
            if let Some(capability) = string_at(command, "provider_capability") {
                let _ = writeln!(page, "| provider capability | `{capability}` |");
            }
            let _ = writeln!(
                page,
                "| privilege | {} |",
                string_at(command, "privilege").unwrap_or_else(|| "none".to_owned())
            );
            let _ = writeln!(
                page,
                "| arguments | parsed in {} mode (ADR-0009) |",
                string_at(command, "argument_mode").unwrap_or_else(|| "words".to_owned())
            );

            let selectors = sequence(command, "selectors");
            if !selectors.is_empty() {
                let _ = write!(
                    page,
                    "\n**Selectors**\n\n| name | type | meaning |\n|---|---|---|\n"
                );
                for selector in selectors {
                    let _ = writeln!(
                        page,
                        "| `{}` | `{}` | {} |",
                        string_at(selector, "name").unwrap_or_default(),
                        string_at(selector, "type").unwrap_or_default(),
                        string_at(selector, "doc").unwrap_or_default()
                    );
                }
            }

            let options = sequence(command, "options");
            if !options.is_empty() {
                let _ = write!(
                    page,
                    "\n**Options**\n\n| name | type | meaning |\n|---|---|---|\n"
                );
                for option in options {
                    let _ = writeln!(
                        page,
                        "| `--{}` | `{}` | {} |",
                        string_at(option, "name").unwrap_or_default(),
                        string_at(option, "type").unwrap_or_default(),
                        string_at(option, "doc").unwrap_or_default()
                    );
                }
            }

            let examples = string_sequence(command, "examples");
            if !examples.is_empty() {
                page.push_str("\n**Examples**\n\n```text\n");
                for example in examples {
                    let _ = writeln!(page, "{example}");
                }
                page.push_str("```\n");
            }
        }
    }
    page
}

