//! Generating `docs/reference/` from the registries (spec §36.2).
//!
//! Spec §36 is explicit that the machine-readable registries "become executable contracts" and
//! that documentation is derived from them. Deriving it is only half the job: the gate also
//! compares what is committed against what the generator produces, because a generator nobody
//! checks against the tree is a generator whose output has quietly diverged
//! (`docs/ACCEPTANCE.md` §4.5).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_yaml_ng::Value as Yaml;

pub use crate::scan::Problem;

/// The banner every generated page carries.
const BANNER: &str = "<!-- generated by `cargo xtask docs` from docs/spec/. Do not edit by hand: \
your changes will be overwritten and the gate will fail (AGENTS.md section 2). -->";

/// One generated page.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Page {
    /// Where the page belongs, relative to the repository root.
    pub path: String,
    /// The page's complete contents.
    pub contents: String,
}

/// Why generation could not run.
#[derive(Debug)]
pub struct GenerateError {
    /// What went wrong, phrased for the reader.
    pub detail: String,
}

impl std::fmt::Display for GenerateError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.detail)
    }
}

impl std::error::Error for GenerateError {}

/// Generates every reference page from the registries under `root/docs/spec`.
///
/// # Errors
///
/// Returns a [`GenerateError`] if `docs/spec/` is missing or a registry is not valid YAML.
pub fn generate(root: &Path) -> Result<Vec<Page>, GenerateError> {
    let spec = root.join("docs").join("spec");
    if !spec.is_dir() {
        return Err(GenerateError {
            detail: format!("{} does not exist", spec.display()),
        });
    }

    let verbs = load(&spec.join("verbs.yaml"))?;
    let targets = load(&spec.join("targets.yaml"))?;
    let errors = load(&spec.join("errors.yaml"))?;
    let capabilities = load(&spec.join("capabilities.yaml"))?;
    let schemas = load_directory(&spec.join("schemas"))?;
    let commands = load_directory(&spec.join("commands"))?;
    let packs = load_packs(&spec.join("adapters").join("first-party"))?;
    let streaming = load(&spec.join("hardening").join("streaming_classification.yaml"))?;

    let mut pages = vec![
        Page {
            path: "docs/reference/README.md".to_owned(),
            contents: index_page(),
        },
        Page {
            path: "docs/reference/commands.md".to_owned(),
            contents: commands_page(&commands),
        },
        Page {
            path: "docs/reference/verbs.md".to_owned(),
            contents: verbs_page(verbs.as_ref()),
        },
        Page {
            path: "docs/reference/targets.md".to_owned(),
            contents: targets_page(targets.as_ref()),
        },
        Page {
            path: "docs/reference/schemas.md".to_owned(),
            contents: schemas_page(&schemas),
        },
        Page {
            path: "docs/reference/errors.md".to_owned(),
            contents: errors_page(errors.as_ref()),
        },
        Page {
            path: "docs/reference/capabilities.md".to_owned(),
            contents: capabilities_page(capabilities.as_ref()),
        },
        Page {
            path: "docs/reference/streaming.md".to_owned(),
            contents: streaming_page(streaming.as_ref()),
        },
        Page {
            path: "docs/reference/terminology.md".to_owned(),
            contents: terminology_page(),
        },
        Page {
            path: "docs/reference/remote-trust.md".to_owned(),
            contents: remote_trust_page(),
        },
        Page {
            path: "docs/reference/release-verification.md".to_owned(),
            contents: release_verification_page(),
        },
    ];
    if !packs.is_empty() {
        pages.push(Page {
            path: "docs/reference/adapters/README.md".to_owned(),
            contents: adapters_matrix_page(&packs),
        });
        for pack in &packs {
            pages.push(Page {
                path: format!("docs/reference/adapters/{}.md", pack.id()),
                contents: adapter_pack_page(pack),
            });
        }
    }
    Ok(pages)
}

/// Compares the committed reference docs with what the registries would produce.
#[must_use]
pub fn check_committed(root: &Path) -> Vec<Problem> {
    let generated = match generate(root) {
        Ok(pages) => pages,
        Err(_) => return Vec::new(),
    };

    let mut problems = Vec::new();
    for page in generated {
        let path = root.join(&page.path);
        match std::fs::read_to_string(&path) {
            Ok(committed) if committed == page.contents => {}
            Ok(_) => problems.push(Problem {
                location: page.path.clone(),
                detail: "does not match what the registries produce; run `cargo xtask docs` \
                         (spec §36.2). If the difference is deliberate, the registry is where it \
                         belongs, not the page"
                    .to_owned(),
            }),
            Err(_) => problems.push(Problem {
                location: page.path.clone(),
                detail: "is missing; run `cargo xtask docs`".to_owned(),
            }),
        }
    }
    problems
}

/// Writes every generated page to disk.
///
/// # Errors
///
/// Returns a [`GenerateError`] if generation fails or a page cannot be written.
pub fn write(root: &Path) -> Result<Vec<String>, GenerateError> {
    let mut written = Vec::new();
    for page in generate(root)? {
        let path = root.join(&page.path);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|error| GenerateError {
                detail: format!("cannot create {}: {error}", parent.display()),
            })?;
        }
        std::fs::write(&path, &page.contents).map_err(|error| GenerateError {
            detail: format!("cannot write {}: {error}", path.display()),
        })?;
        written.push(page.path);
    }
    Ok(written)
}

